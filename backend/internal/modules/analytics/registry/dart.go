package registry

import (
	"bytes"
	"fmt"
	"sort"
	"strings"
)

// Dart renders the app's constants from the registry: event names and
// versions (app events only, so the app has no constant for an event it may
// not send), screens, flows and their steps, controls, attribute keys and
// enum values. The output is already in `dart format` style.
func (r *Registry) Dart() []byte {
	var b bytes.Buffer
	b.WriteString("// GENERATED by `go generate ./internal/modules/analytics/registry` from\n")
	b.WriteString("// backend/internal/modules/analytics/registry/events.yaml. Do not edit:\n")
	b.WriteString("// change the registry and regenerate, so the app and the server agree.\n\n")

	var appEvents []string
	keys := map[string]bool{}
	type enumValue struct{ name, value string }
	var enums []enumValue
	for _, name := range r.EventNames() {
		e := r.Events[name]
		if e.Source != SourceApp {
			continue
		}
		appEvents = append(appEvents, name)
		attrs := make([]string, 0, len(e.Attributes))
		for k := range e.Attributes {
			attrs = append(attrs, k)
		}
		sort.Strings(attrs)
		for _, k := range attrs {
			keys[k] = true
			a := e.Attributes[k]
			if a.Type == TypeEnum && a.ValuesFrom == "" {
				for _, v := range a.Values {
					enums = append(enums, enumValue{camel(name + "_" + k + "_" + v), v})
				}
			}
		}
	}

	b.WriteString("/// The event names the server accepts from the app.\n")
	b.WriteString("abstract final class AnalyticsEvent {\n")
	for _, n := range appEvents {
		fmt.Fprintf(&b, "  static const %s = '%s';\n", camel(n), n)
	}
	b.WriteString("}\n\n")

	b.WriteString("/// The schema version of each event, sent as `schema_version`.\n")
	b.WriteString("const Map<String, int> analyticsEventVersions = {\n")
	for _, n := range appEvents {
		fmt.Fprintf(&b, "  AnalyticsEvent.%s: %d,\n", camel(n), r.Events[n].Version)
	}
	b.WriteString("};\n\n")

	writeClass(&b, "The screen catalogue: the only values `screen` may take.", "AnalyticsScreen", "", r.Screens)

	b.WriteString("/// The funnels: the only values `flow_id` may take.\n")
	b.WriteString("abstract final class AnalyticsFlow {\n")
	for _, f := range r.FlowNames() {
		fmt.Fprintf(&b, "  static const %s = '%s';\n", camel(f), f)
	}
	b.WriteString("}\n\n")

	b.WriteString("/// The steps of each funnel, in order: the only values `flow_step` may take.\n")
	b.WriteString("const Map<String, List<String>> analyticsFlowSteps = {\n")
	for _, f := range r.FlowNames() {
		quoted := make([]string, len(r.Flows[f]))
		for i, s := range r.Flows[f] {
			quoted[i] = "'" + s + "'"
		}
		line := fmt.Sprintf("  AnalyticsFlow.%s: [%s],\n", camel(f), strings.Join(quoted, ", "))
		if len(line) > 81 {
			line = fmt.Sprintf("  AnalyticsFlow.%s: [\n    %s,\n  ],\n", camel(f), strings.Join(quoted, ",\n    "))
		}
		b.WriteString(line)
	}
	b.WriteString("};\n\n")

	b.WriteString("/// Each funnel's steps, named flow then step.\n")
	b.WriteString("abstract final class AnalyticsFlowStep {\n")
	for _, f := range r.FlowNames() {
		for _, step := range r.Flows[f] {
			fmt.Fprintf(&b, "  static const %s = '%s';\n", camel(f+"_"+step), step)
		}
	}
	b.WriteString("}\n\n")

	writeClass(&b, "The catalogued controls `cta_tapped` may name.", "AnalyticsCta", "", r.CTAs)

	attrKeys := make([]string, 0, len(keys))
	for k := range keys {
		attrKeys = append(attrKeys, k)
	}
	sort.Strings(attrKeys)
	writeClass(&b, "Attribute keys.", "AnalyticsAttribute", "", attrKeys)

	b.WriteString("/// Values of the enum attributes, named event, attribute, value.\n")
	b.WriteString("abstract final class AnalyticsValue {\n")
	for _, e := range enums {
		fmt.Fprintf(&b, "  static const %s = '%s';\n", e.name, e.value)
	}
	b.WriteString("}\n")
	return b.Bytes()
}

func writeClass(b *bytes.Buffer, doc, class, prefix string, values []string) {
	fmt.Fprintf(b, "/// %s\n", doc)
	fmt.Fprintf(b, "abstract final class %s {\n", class)
	for _, v := range values {
		fmt.Fprintf(b, "  static const %s = '%s';\n", camel(prefix+v), v)
	}
	b.WriteString("}\n\n")
}

// camel turns snake_case (and . : -) into lowerCamelCase.
func camel(s string) string {
	parts := strings.FieldsFunc(s, func(r rune) bool { return r == '_' || r == '.' || r == ':' || r == '-' })
	for i := 1; i < len(parts); i++ {
		parts[i] = strings.ToUpper(parts[i][:1]) + parts[i][1:]
	}
	return strings.Join(parts, "")
}
